export type SortKey = "latest" | "trending" | "most-read" | "market-impact";

export const sortOptions: { key: SortKey; label: string }[] = [
  { key: "latest", label: "Latest" },
  { key: "trending", label: "Trending" },
  { key: "most-read", label: "Most Read" },
  { key: "market-impact", label: "Market Impact" },
];

export function sortArticles(list: Article[], key: SortKey): Article[] {
  const copy = [...list];
  if (key === "trending") return copy.sort((a, b) => b.trending - a.trending);
  if (key === "most-read") return copy.sort((a, b) => b.reads - a.reads);
  if (key === "market-impact")
    return copy.sort((a, b) => b.marketImpact - a.marketImpact || b.trending - a.trending);
  return copy;
}

export function byCategory(slug: string) {
  return articles.filter((a) => a.category === slug);
}

export function bySubcategory(category: string, subcategory: string) {
  return articles.filter((a) => a.category === category && a.subcategory === subcategory);
}

export function byTopic(slug: string) {
  return articles.filter((a) => a.topics.includes(slug));
}

export function byAsset(symbol: string) {
  return articles.filter((a) => a.assets.includes(symbol));
}

export function byFormat(format: ContentFormat | ContentFormat[]) {
  const list = Array.isArray(format) ? format : [format];
  return articles.filter((a) => list.includes(a.format));
}

export function findArticle(slug: string) {
  return articles.find((a) => a.slug === slug);
}

export function relatedArticles(article: Article, limit = 4) {
  return articles
    .filter((a) => a.id !== article.id)
    .map((a) => ({
      a,
      score:
        (a.category === article.category ? 2 : 0) +
        a.topics.filter((t) => article.topics.includes(t)).length +
        a.assets.filter((s) => article.assets.includes(s)).length,
    }))
    .filter((x) => x.score > 0)
    .sort((x, y) => y.score - x.score)
    .slice(0, limit)
    .map((x) => x.a);
}

